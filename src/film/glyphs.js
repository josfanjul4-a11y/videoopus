// Add text to a LineBatch, centred at `center` in the XY plane, cap height h.
// Strokes are revealed in reading order (u runs across the whole text).
export function strokeText(batch, text, center, h, { width = 1.3, spacing = 0.25, intensity = 1, align = 'center' } = {}) {
  const chars = [...text.toUpperCase()].map((c) => GLYPHS[c] ?? GLYPHS[' ']);
  const total = chars.reduce((a, g) => a + g.w, 0) + spacing * (chars.length - 1);
  let x = align === 'center' ? -total / 2 : 0;
  const nStrokes = chars.reduce((a, g) => a + g.s.length, 0) || 1;
  let k = 0;
  for (const g of chars) {
    for (const stroke of g.s) {
      const pts = stroke.map(([px, py]) => [center[0] + (x + px) * h, center[1] + (py - 0.5) * h, center[2]]);
      batch.polyline(pts, { width, intensity, u0: k / nStrokes, u1: (k + 1) / nStrokes, hi: 0.4 });
      k++;
    }
    x += g.w + spacing;
  }
  return batch;
}
