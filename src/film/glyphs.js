// A tiny stroke font: every letter is a few polylines in a unit box
// (x 0..w, y 0..1). No font files are used anywhere; text is drawn with the
// hairline renderer, so it has the same gold, antialiased line as the film.

const arc = (cx, cy, rx, ry, a0, a1, n = 16) => Array.from({ length: n + 1 }, (_, i) => {
  const a = a0 + ((a1 - a0) * i) / n;
  return [cx + Math.cos(a) * rx, cy + Math.sin(a) * ry];
});

